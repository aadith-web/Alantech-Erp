#!/usr/bin/env bash
# Concatenates the desk-only scripts into one file, in the same order as app_include_js in hooks.py.
# Re-run this after editing any source script in alantech_erp/public/js.
set -euo pipefail
cd "$(dirname "$0")/../alantech_erp/public/js"
FILES=(
  csrf_bridge.js
  employee_profile_upload.js
  phone_control.js
  customer_quick_entry.js
  checkin_reminder.js
  notification_read.js
  employee_company_policy_list.js
  asset_assign_override.js
  sales_activity.js
  loan_applicant_name.js
)
OUT=alantech_desk_bundle.js
{
  echo "/* Generated by scripts/build_desk_bundle.sh. Do not edit by hand. */"
  for f in "${FILES[@]}"; do
    echo ";/* ---- $f ---- */"
    cat "$f"
    echo
  done
} > "$OUT"
echo "wrote $OUT ($(wc -c < "$OUT") bytes)"
